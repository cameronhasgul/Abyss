"""Write docs/results.md from the benchmark output, so its numbers can't drift from it.

    python -m abyss.evaluation.report
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PLANNER_NAMES = {
    "abyss": "ABYSS",
    "frontier": "Frontier",
    "heuristic": "Heuristic",
    "lawnmower": "Lawnmower",
    "random": "Random",
    "abyss_no_info": "No uncertainty",
    "abyss_no_learning": "No learning",
}
WORLD_NAMES = {
    "random": "Independent random",
    "clustered": "Spatial clusters",
    "ridge": "Ridge-associated",
    "reversed": "Flat-associated",
    "nonlinear": "Nonlinear mixed",
}
TERRAIN_NAMES = {"gebco": "GEBCO Monterey Canyon crop", "synthetic": "Synthetic terrain, one per seed"}


def _world(data: dict, terrain: str, scenario: str, rho: float) -> dict:
    return next(
        w for w in data["worlds"]
        if (w["terrain"], w["scenario"], w["rho"]) == (terrain, scenario, rho)
    )


def _label(world: dict) -> str:
    name = WORLD_NAMES[world["scenario"]]
    return name if world["scenario"] == "random" else f"{name}, signal {world['rho']:g}"


def _diff(data: dict, other: str, scenario: str, rho: float, terrain: str = "gebco") -> str:
    c = _world(data, terrain, scenario, rho)["abyss_vs"][other]
    return f"{c['mean_difference']:+.2f} [{c['ci95_low']:+.2f}, {c['ci95_high']:+.2f}]"


def _means_table(data: dict, terrain: str) -> list[str]:
    planners = list(PLANNER_NAMES)
    lines = [
        "| World | " + " | ".join(PLANNER_NAMES[p] for p in planners) + " |",
        "| --- |" + " --- |" * len(planners),
    ]
    for world in (w for w in data["worlds"] if w["terrain"] == terrain):
        means = [world["planners"][p]["mean"] for p in planners]
        lines.append(f"| {_label(world)} | " + " | ".join(f"{m:.2f}" for m in means) + " |")
    return lines


def _comparison_table(data: dict, terrain: str) -> list[str]:
    others = [p for p in PLANNER_NAMES if p != "abyss"]
    lines = [
        "| World | " + " | ".join(f"vs {PLANNER_NAMES[p]}" for p in others) + " |",
        "| --- |" + " --- |" * len(others),
    ]
    for world in (w for w in data["worlds"] if w["terrain"] == terrain):
        cells = []
        for other in others:
            c = world["abyss_vs"][other]
            mark = "**" if c["ci95_low"] > 0 or c["ci95_high"] < 0 else ""
            cells.append(f"{mark}{c['mean_difference']:+.2f}{mark} [{c['ci95_low']:+.2f}, {c['ci95_high']:+.2f}]")
        lines.append(f"| {_label(world)} | " + " | ".join(cells) + " |")
    return lines


def render(data: dict) -> str:
    safety = data["safety"]
    d = lambda *args, **kwargs: _diff(data, *args, **kwargs)  # noqa: E731
    lines = [
        "# ABYSS benchmark results",
        "",
        "Generated by `python -m abyss.evaluation.report` from executed missions. Regenerate it",
        "rather than editing it by hand.",
        "",
        f"**Setup:** {safety['missions']} missions over {len(data['seeds'])} evaluation seeds, with",
        f"{safety['safe_returns']} safe returns and {safety['forced_returns']} forced returns. Each planner",
        "gets the same worlds, energy budget and sensing. The metric is distinct categories found",
        f"within the energy budget, out of {data['frozen_config']['simulation']['n_categories']}, scored on true labels. Differences are ABYSS",
        "minus the other planner, shown as the mean and a 95% paired bootstrap interval.",
        "",
        "## Findings",
        "",
        "Differences below use the GEBCO crop, unless they say otherwise.",
        "",
        "1. **ABYSS beats conventional surveying when habitat predicts biodiversity.** Against",
        f"   frontier it gains {d('frontier', 'ridge', 0.25)} at signal 0.25 and {d('frontier', 'ridge', 1.0)} at",
        f"   signal 1 on ridge worlds, and {d('frontier', 'reversed', 1.0)} on flat-associated worlds at signal 1.",
        f"2. **It shows no clear gain without usable structure.** Against frontier: {d('frontier', 'random', 0.0)}",
        "   in the independent random world. This also fits the leakage tests: a planner",
        "   secretly reading hidden data would have no reason to stop there.",
        f"3. **Learning has a measurable cost when there's nothing to learn.** In the random world,",
        f"   ABYSS against its own no-learning version is {d('abyss_no_learning', 'random', 0.0)}. On synthetic",
        f"   terrain the same comparison is {d('abyss_no_learning', 'random', 0.0, terrain='synthetic')}, which is not clear.",
        "4. **Our spatial-cluster hypothesis was not supported.** ABYSS uses terrain features, and",
        f"   clusters here are independent of terrain. Against frontier: {d('frontier', 'clustered', 1.0)} on",
        f"   GEBCO and {d('frontier', 'clustered', 1.0, terrain='synthetic')} on synthetic terrain.",
        "5. **Learning protects against a wrong assumption.** The fixed steep-ground heuristic is close",
        f"   to ABYSS when its assumption roughly holds ({d('heuristic', 'ridge', 0.25)} at ridge signal 0.25),",
        f"   but far behind when it is wrong ({d('heuristic', 'reversed', 1.0)} on flat-associated worlds at signal 1).",
        "6. **The uncertainty term's value is mixed.** ABYSS minus its no-uncertainty version is "
        f"{d('abyss_no_info', 'reversed', 1.0)} on",
        f"   flat-associated worlds at signal 1, but {d('abyss_no_info', 'reversed', 0.25, terrain='synthetic')} at signal 0.25 on",
        "   synthetic terrain, where the version without uncertainty does better.",
        "",
        "## Limitations",
        "",
        "- **Biology is simulated.** These results show behaviour in worlds we designed, not real",
        "  ocean ecology. Several worlds use features ABYSS's model can represent, which helps it.",
        "- **Ideal perception only.** These runs use simulator labels. The planned comparison of ideal",
        "  and real perception has not been run.",
        "- **One real terrain crop.** GEBCO seeds share one crop, so they vary the biology but not the",
        "  region. Synthetic terrain varies by seed, but it isn't real bathymetry.",
        "- **Ceiling effects.** Results near the maximum category count understate differences.",
        "- **Many comparisons.** Intervals are not corrected for multiple comparisons, so treat",
        "  borderline results with caution.",
        "- **Simple target.** The model predicts richness rather than new categories, so a rich site",
        "  holding only known organisms still looks valuable.",
        "- **Abstract energy.** Energy units and travel costs are not measured from a real vehicle.",
        "",
        "ABYSS settings were chosen on separate development seeds and frozen before evaluation.",
        "",
    ]
    for terrain in TERRAIN_NAMES:
        lines += [f"## {TERRAIN_NAMES[terrain]}", "", "Mean categories found:", ""]
        lines += _means_table(data, terrain)
        lines += ["", "ABYSS minus each planner. Bold means the 95% interval excludes zero:", ""]
        lines += _comparison_table(data, terrain)
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--summary", type=Path, default=Path("ui/logs/benchmark.json"))
    parser.add_argument("--out", type=Path, default=Path("docs/results.md"))
    args = parser.parse_args()
    data = json.loads(args.summary.read_text(encoding="utf-8"))
    args.out.write_text(render(data), encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
